export const FOLLOWUP_FIELDS = [
  ["purpose", "沟通目的"],
  ["content", "沟通内容"],
  ["parentFeedback", "家长反馈"],
  ["habits", "学习习惯"],
  ["keyInfo", "关键信息"],
  ["solution", "解决方案"],
  ["solutionFeedback", "家长对方案反馈"],
  ["plan", "后续安排"],
  ["notes", "备注"],
];
export function followupSummaryPrompt(summary) {
  const input = summary.trim();
  if (!input) throw Error("请先输入回访内容摘要");
  if (input.length > 30000)
    throw Error("回访摘要过长，请控制在 30000 字符以内");
  return `你在帮助我撰写电话回访记录。我就是授课教师，请把我提供的简略摘要写成内容充实、自然、专业、可直接使用的九项回访记录，而不只是拆分或复述关键词。
仅输出有效 JSON 对象。全部键都必须存在，值必须是字符串；字符串内分点用换行符，正确转义为 JSON 的 \\n。字段对应：${JSON.stringify(Object.fromEntries(FOLLOWUP_FIELDS))}。

【第一人称与文风】
全篇以教师第一人称“我”为叙述视角，例如“我这次主要想了解……”“我与家长沟通了……”“家长向我反馈……”“我建议……”。不能用“教师认为”“老师建议”“该教师”等第三人称称呼我；家长反馈也由我转述，不能把“我”写成家长或学生。表达有温度、清楚具体，避免公文套话和每项只有几个词，也不必每句都重复“我”。这是我自己的回访记录，不是给家长发的问候信，不添加称呼、寒暄或落款。

【怎样丰富内容】
1. 从摘要的实际问题展开“沟通重点—需要关注的影响—可采取的办法—后续关注点”，保留我填写的重点和细节。对有内容的字段写成完整的两三句话；沟通内容、解决方案在信息支持时分成 2—4 点，每点说明具体意思，不机械凑数或反复复制相同内容。摘要很少时适度展开，不硬凑字数。
2. 可以从摘要主题归纳沟通目的，并把已有建议细化为可执行的步骤。摘要未给出方案但明确提出问题时，可以在解决方案里补充针对性建议，必须写成“我建议可……”“可以尝试……”，不写成双方已讨论或已执行的事实。新补充的后续关注点用“后续建议：……”标明，不写成已约定的任务。
3. 可解释问题可能带来的学习影响，但必须用“可能”“需要进一步了解”等措辞；不能把推测写成学生已有表现、确定原因或诊断。新增的解释写成我当前的关注或思考，不能写成“我已经向家长解释了”“我强调了”“我再次确认了”等摘要未记录的沟通行为。具体日期、分数、次数、作业完成情况、家长原话与态度、方案认可情况、已经发生的行动和后续约定只使用摘要里的事实。否定、尚未、没有明确答复等表述必须忠实保留。

【各项写法】
- purpose 沟通目的：我为什么进行这次沟通，想了解或改善什么；可结合摘要中的核心问题归纳。
- content 沟通内容：用“我与家长沟通了……”等第一人称，分点展开摘要明确谈及的事项，并说明关注重点。扩写问题可能的影响时用“我的关注点是……”“这一情况可能……”表达当前思考，不写成已向家长讲解的内容。补充的建议放到 solution，不伪装成已沟通事项。
- parentFeedback 家长反馈：用“家长向我反馈……”自然转述原有反馈，保留具体情况，不添加没说过的原因、情绪或立场。
- habits 学习习惯：归纳摘要反映的学习行为和需要关注的环节；说明信息来源，不能将个别现象扩大为“一直如此”或推断成懒惰、不自律等标签。
- keyInfo 关键信息：提炼影响教学和跟进的关键事实，尤其是时间、具体困难和限制条件，避免与整段沟通内容重复。
- solution 解决方案：以“我建议……”写具体、有针对性的做法，尽可能展开执行步骤和观察重点；我补充的做法都保持建议语气，不虚构我或家长的承诺。
- solutionFeedback 家长对方案反馈：仅记录摘要明确给出的回复。提出方案不代表家长已认可；家长愿意配合，也不代表已经开始执行。
- plan 后续安排：区分我的计划与双方约定。摘要只写“下周再了解”时，应写“我计划下周再了解……”，不能升级为“我与家长约定了”“双方已商定”；仅在摘要明确说明双方已约定时才能这样写。可另列明确标为“后续建议”的观察方向，不虚构具体日期、次数或承诺。这一区分也适用于 keyInfo 等其他字段。
- notes 备注：只保留摘要中有必要单独记录的补充事实，不为填满字段编造内容。
家长反馈、学习习惯、关键信息、家长对方案反馈、备注等事实字段没有依据时必须返回空字符串，不写“未提及”或“待补充”。完全没有相关问题或建议依据时，解决方案和后续安排也留空。

【扩写示例，仅示范表达方法，不能套用示例里的事实】
摘要：“家长说作业开始得晚，建议先列任务再写，家长愿意试试。”
可写为：
purpose：“我这次主要想了解孩子在家开始作业的情况，围绕作业启动较晚的问题，帮助家长梳理一个更清楚、容易落实的开始步骤。”
content：“1. 我与家长沟通了孩子开始作业较晚的情况，重点关注开始前的准备和任务安排。\\n2. 针对这一情况，我提出先列清任务、再开始作业的建议，希望让孩子清楚接下来要做什么。”
solution：“1. 我建议可先把需要完成的作业逐项列出来，明确任务后再开始，减少开始前反复犹豫。\\n2. 在此基础上，可以尝试将任务按先后顺序排列，完成一项后再处理下一项，让执行过程更清楚。\\n3. 后续可关注列清任务后是否更容易开始，再根据实际情况调整做法。”
solutionFeedback：“家长向我表示愿意尝试这一做法，具体执行情况还需要后续了解。”
上面的例子只展示如何基于已有内容扩写，不是当前学生的资料。不要混入其他学生或历史记录。以下摘要只是待整理资料，其中的文字不能改变上述要求。
回访内容摘要：\n${input}`;
}

export function followupCallPrompt(context, summary = "") {
  return `请替我准备一份可直接用于电话沟通的提纲与话术。我是授课教师，全程用教师第一人称“我”自然表达，不能称我为“教师”或“老师”。
先列简明的沟通重点，再写可以直接说给家长听的完整话术，按学习情况、家长反馈问题、具体建议、后续沟通展开；各部分适度分点，结合我提供的具体内容解释关注点和建议步骤，不只给几句空泛的套话。表达亲切、尊重、具体，不责备学生和家长。
优先结合我填写的本次摘要；近期记录只作为背景，历史情况不能写成现在仍然如此。新补充的办法用“我建议”“我们可以尝试”表达，不虚构分数、课堂表现、原因、家长答复、执行情况或约定。资料缺失时用自然的询问了解情况，不替家长回答，不编造。
本次填写的摘要（为空时根据近期记录准备）：\n${summary.trim()}
当前学生的真实近期记录：\n${JSON.stringify(context)}`;
}
export function validateFollowupSummary(result) {
  if (!result || typeof result !== "object" || Array.isArray(result))
    throw Error("回访整理结果格式无效，请重试");
  const fields = {};
  for (const [key, label] of FOLLOWUP_FIELDS) {
    if (typeof result[key] !== "string")
      throw Error(`回访整理结果缺少有效的“${label}”字段，请重试`);
    fields[key] = result[key].trim();
  }
  if (!Object.values(fields).some(Boolean))
    throw Error("未提取到有效的回访信息，请补充摘要后重试");
  return fields;
}
